export function getTranslation(lang, path, fallback = '') {
  if (!path || typeof path !== 'string') return fallback || '';
  const currentLang = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const parts = path.split('.');
  let val = currentLang;
  for (const part of parts) {
    if (val && typeof val === 'object' && part in val) {
      val = val[part];
    } else {
      // fallback to english
      let enVal = TRANSLATIONS.en;
      for (const p of parts) {
        if (enVal && typeof enVal === 'object' && p in enVal) {
          enVal = enVal[p];
        } else {
          return fallback || path;
        }
      }
      val = enVal;
      break;
    }
  }
  if (val && typeof val === 'object') {
    if (val[lang] && typeof val[lang] === 'string') return val[lang];
    if (val.en && typeof val.en === 'string') return val.en;
    return fallback || '';
  }
  return val !== undefined ? val : (fallback || path);
}
