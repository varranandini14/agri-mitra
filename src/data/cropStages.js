/**
 * Get the stage list for a given crop id.
 * Returns array of stages or empty array if crop not found.
 */
export function getCropStages(cropId) {
  return CROP_STAGES[cropId] || [];
}

/**
 * Calculate the estimated current stage and stage timeline based on sowing date.
 * If the sowing date is in the future, invalid, or past the expected harvest window,
 * returns an informative status object.
 *
 * @param {string} cropId
 * @param {string} sowingDateStr - ISO date string YYYY-MM-DD
 * @returns {object} {
 *   status: 'valid' | 'future' | 'invalid_date' | 'past_harvest',
 *   daysSinceSowing: number,
 *   stages: Array,
 *   estimatedStageIndex: number,
 *   estimatedStage: object | null,
 *   harvestWindow: { minDate: string, maxDate: string, minDays: number, maxDays: number }
 * }
 */
export function calculateCropTimeline(cropId, sowingDateStr) {
  const stages = getCropStages(cropId);
  if (!stages || stages.length === 0) {
    return {
      status: 'no_crop_data',
      message: 'No stage data available for this crop.',
      stages: [],
    };
  }

  if (!sowingDateStr || isNaN(Date.parse(sowingDateStr))) {
    return {
      status: 'invalid_date',
      message: 'Please provide a valid planting date.',
      stages,
      estimatedStageIndex: 0,
      estimatedStage: stages[0],
    };
  }

  // Calculate day difference using UTC to avoid timezone day shifts
  const [sYear, sMonth, sDay] = sowingDateStr.split('-').map(Number);
  const sowDateUtc = Date.UTC(sYear, sMonth - 1, sDay);
  const now = new Date();
  const todayUtc = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate());

  const msPerDay = 1000 * 60 * 60 * 24;
  const daysSinceSowing = Math.floor((todayUtc - sowDateUtc) / msPerDay);

  const lastStage = stages[stages.length - 1];
  const minTotalDays = stages[0]?.cumulativeDays?.minDays ?? 0;
  const maxTotalDays = lastStage?.cumulativeDays?.maxDays ?? 120;

  // Calculate estimated harvest window
  const minHarvestMs = sowDateUtc + (lastStage?.cumulativeDays?.minDays ?? (maxTotalDays - 15)) * msPerDay;
  const maxHarvestMs = sowDateUtc + maxTotalDays * msPerDay;
  const minHarvestDate = new Date(minHarvestMs).toISOString().slice(0, 10);
  const maxHarvestDate = new Date(maxHarvestMs).toISOString().slice(0, 10);

  const harvestWindow = {
    minDate: minHarvestDate,
    maxDate: maxHarvestDate,
    minDays: lastStage?.cumulativeDays?.minDays ?? (maxTotalDays - 15),
    maxDays: maxTotalDays,
  };

  // 1. Future date check
  if (daysSinceSowing < 0) {
    return {
      status: 'future',
      daysSinceSowing,
      daysUntil: Math.abs(daysSinceSowing),
      message: 'Planting date is in the future. Timeline starts on the entered sowing date.',
      stages,
      estimatedStageIndex: 0,
      estimatedStage: stages[0],
      harvestWindow,
    };
  }

  // 2. Far past harvest window check (+45 days grace)
  if (daysSinceSowing > maxTotalDays + 45) {
    return {
      status: 'past_harvest',
      daysSinceSowing,
      message: 'This crop is past its typical harvest window. Did you harvest already or keep it in the field?',
      stages,
      estimatedStageIndex: stages.length - 1,
      estimatedStage: lastStage,
      harvestWindow,
    };
  }

  // 3. Normal estimation from cumulative ranges
  let matchedIdx = 0;
  for (let i = 0; i < stages.length; i++) {
    const st = stages[i];
    if (daysSinceSowing >= st.cumulativeDays.minDays && daysSinceSowing <= st.cumulativeDays.maxDays) {
      matchedIdx = i;
      break;
    }
    if (daysSinceSowing > st.cumulativeDays.maxDays) {
      matchedIdx = i; // move forward as days advance
    }
  }

  return {
    status: 'valid',
    daysSinceSowing,
    stages,
    estimatedStageIndex: matchedIdx,
    estimatedStage: stages[matchedIdx],
    harvestWindow,
  };
}

/**
 * Format estimated harvest window nicely in words
 */
export function formatHarvestWindowText(harvestWindow, language = 'en') {
  if (!harvestWindow) return '';
  const { minDate, maxDate } = harvestWindow;

  function toDateStr(iso) {
    if (!iso) return '';
    const d = new Date(iso);
    return d.toLocaleDateString(language === 'te' ? 'te-IN' : language === 'hi' ? 'hi-IN' : 'en-IN', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  }

  const minStr = toDateStr(minDate);
  const maxStr = toDateStr(maxDate);

  if (language === 'te') {
    return `సుమారు ${minStr} నుండి ${maxStr} మధ్య`;
  }
  if (language === 'hi') {
    return `लगभग ${minStr} से ${maxStr} के बीच`;
  }
  return `Around ${minStr} to ${maxStr}`;
}
